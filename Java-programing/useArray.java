// Experiment Name: Write a Java program to use an Array.

// Objective: To store and display multiple values using an Array in Java.

// Required Equipment: Computer, JDK (Java Development Kit), IntelliJ IDEA.

// Program: Write the following Java code and run it.

 public class useArray {
     public static void main(String[] args) {
         int[] numbers = {10, 20, 30, 40, 50};

         System.out.println("Array Elements:");

         for (int number : numbers) {
             System.out.println(number);
         }
     }
 }

// Output:
// Array Elements:
// 10
// 20
// 30
// 40
// 50

// Comment: An Array is used to store multiple values of the same data type in a single variable. The for loop is used to access each element of the Array.